// Build src/data/addresses.index.ts: the addresses of the pages that exist (cases that are published, glossary / law / FAQ
// pages that are not drafts). A link in a text to an address of this site that is not in this list (and is not one of the
// fixed pages) is shown as plain text until the page exists (src/lib/known-addresses.ts), so the site never publishes a
// broken link. The link becomes a real link by itself when the page is added. Runs before every build and dev start.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "src", "data", "addresses.index.ts");
const addrs = [];
const titles = {};

const casesDir = path.join(ROOT, "content", "cases");
for (const f of fs.readdirSync(casesDir).filter((x) => x.endsWith(".json")).sort()) {
  const c = JSON.parse(fs.readFileSync(path.join(casesDir, f), "utf8"));
  if ((c.status ?? "published") !== "published") continue;
  const a = c.jurisdictionGroup === "country" ? `/${c.jurisdictionSlug}/${c.slug}` : `/us/${c.slug}`;
  addrs.push(a);
  titles[a] = c.title;
}
const walk = (d, acc = []) => {
  if (!fs.existsSync(d)) return acc;
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (e.name.endsWith(".json")) acc.push(p);
  }
  return acc.sort();
};
const pagesDir = path.join(ROOT, "content", "pages");
for (const f of walk(pagesDir)) {
  const p = JSON.parse(fs.readFileSync(f, "utf8"));
  if (p.status === "draft") continue;
  const a = "/" + path.relative(pagesDir, f).split(path.sep).join("/").replace(/\.json$/, "");
  addrs.push(a);
  titles[a] = p.title;
}
addrs.sort();
const out = `// GENERATED by scripts/build-address-index.mjs. Do not edit by hand.\nexport const knownAddresses: string[] = ${JSON.stringify(addrs, null, 2)};\n`;
if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== out) fs.writeFileSync(OUT, out);
// the titles of the pages, for the label of the Back button ("Back to <title>")
const TOUT = path.join(ROOT, "src", "data", "titles.index.ts");
const sortedTitles = Object.fromEntries(Object.entries(titles).sort(([a], [b]) => a.localeCompare(b)));
const tout = `// GENERATED by scripts/build-address-index.mjs. Do not edit by hand.\nexport const pageTitles: Record<string, string> = ${JSON.stringify(sortedTitles, null, 2)};\n`;
if (!fs.existsSync(TOUT) || fs.readFileSync(TOUT, "utf8") !== tout) fs.writeFileSync(TOUT, tout);
console.log(`address index: ${addrs.length} page(s), ${Object.keys(sortedTitles).length} title(s)`);
