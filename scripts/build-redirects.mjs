// Redirects from the old addresses to the new ones, as an nginx map.
//
//   node scripts/build-redirects.mjs            writes deploy/redirects.nginx.map and deploy/redirects.csv
//   node scripts/build-redirects.mjs --check [out-folder]
//                                               checks the built site (default out/): every target exists,
//                                               no old address is still built
//
// Old addresses (live until the move):
//   /cases/[case]                  every US case             -> /us/[case]
//   /usa/federal                                              -> /us/federal
//   /usa/states                                               -> /us/states
//   /usa/states/[state]            every state               -> /us/states/[state]
// Each also with a trailing slash (a trailing slash was an error page, so no page ever linked to it).
// The map is generated from the content, so it cannot drift from the site. It is not installed by
// this repository: the person who manages nginx on the server includes it (see the steps in the handover).
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const ts = require("typescript");
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");

function loadTs(rel) {
  const js = ts.transpileModule(fs.readFileSync(path.join(ROOT, rel), "utf8"), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  }).outputText;
  const mod = { exports: {} };
  const req = (id) => {
    if (id.startsWith("@/types/")) return {};
    if (id.startsWith("./")) return loadTs(path.join(path.dirname(rel), id.slice(2) + ".ts"));
    throw new Error("unexpected import " + id);
  };
  vm.runInNewContext(js, { module: mod, exports: mod.exports, require: req, console });
  return mod.exports;
}

export function oldToNew() {
  const { usStateJurisdictions } = loadTs("src/data/jurisdictions.ts");
  const dir = path.join(ROOT, "content", "cases");
  const rows = [];
  for (const f of fs.readdirSync(dir).filter((x) => x.endsWith(".json")).sort()) {
    const c = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
    if (c.jurisdictionGroup === "country") continue; // country cases were never public at /cases/...
    if ((c.status ?? "published") !== "published") continue;
    rows.push({ old: `/cases/${c.slug}`, next: `/us/${c.slug}`, kind: "case", title: c.title });
  }
  rows.push({ old: "/usa/federal", next: "/us/federal", kind: "listing", title: "USA Federal" });
  rows.push({ old: "/usa/states", next: "/us/states", kind: "listing", title: "USA States" });
  for (const s of usStateJurisdictions) rows.push({ old: `/usa/states/${s.slug}`, next: `/us/states/${s.slug}`, kind: "state", title: s.name });
  return rows;
}

const args = process.argv.slice(2);
if (args.includes("--check")) {
  const out = path.resolve(args[args.indexOf("--check") + 1] && !args[args.indexOf("--check") + 1].startsWith("--") ? args[args.indexOf("--check") + 1] : "out");
  const exists = (p) => fs.existsSync(path.join(out, p + ".html")) || fs.existsSync(path.join(out, p, "index.html"));
  const rows = oldToNew();
  const problems = [];
  for (const r of rows) {
    if (!exists(r.next.slice(1))) problems.push(`target missing: ${r.next} (from ${r.old})`);
    if (exists(r.old.slice(1))) problems.push(`old page still built: ${r.old}`);
  }
  console.log(`${rows.length} redirect(s) checked against ${out}: ${problems.length} problem(s).`);
  for (const p of problems.slice(0, 30)) console.log("  " + p);
  process.exit(problems.length ? 1 : 0);
}

const rows = oldToNew();
const lines = [
  "# GENERATED by scripts/build-redirects.mjs from the case files. Do not edit by hand.",
  "# 301 redirects from the old addresses to the new ones. Not installed by the repository.",
  "# Use in the http {} block:   include /etc/nginx/rdtaxcases-redirects.map;",
  "# and in the rdtaxcases.com server block, before the location blocks:",
  '#   if ($rdtax_redirect) { return 301 $rdtax_redirect; }',
  "map $uri $rdtax_redirect {",
  '    default "";',
  ...rows.flatMap((r) => [`    ${r.old} ${r.next};`, `    ${r.old}/ ${r.next};`]),
  "}",
  "",
];
fs.mkdirSync(path.join(ROOT, "deploy"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "deploy", "redirects.nginx.map"), lines.join("\n"));
const q = (v) => `"${String(v).replace(/"/g, '""')}"`;
fs.writeFileSync(path.join(ROOT, "deploy", "redirects.csv"), "﻿Old address,New address,Kind,Title\r\n" + rows.map((r) => [r.old, r.next, r.kind, r.title].map(q).join(",")).join("\r\n") + "\r\n");
const n = (k) => rows.filter((r) => r.kind === k).length;
console.log(`${rows.length} redirects (${n("case")} cases, ${n("listing")} listing pages, ${n("state")} state pages), each also with a trailing slash: ${rows.length * 2} map lines.`);
