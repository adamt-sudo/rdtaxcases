// Build src/data/pages.index.ts from content/pages/<cc>/<section>/<slug>.json (glossary terms, laws and FAQ
// questions). Like build-case-index.mjs it runs before every build and dev start, and fails the build with a clear
// message when a file is wrong. The address of a page is its path; it is checked with the link spec (page-address.mjs).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadSiteMap, parseAddress } from "./lib/page-address.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const DIR = path.join(ROOT, "content", "pages");
const OUT = path.join(ROOT, "src", "data", "pages.index.ts");
const BLOCK_TYPES = new Set(["paragraph", "heading", "subheading", "list", "table"]);
const STATUSES = new Set(["draft", "preview", "published"]);
const KINDS = new Set(["glossary-term", "legislation-page", "faq-question"]);

function walk(d, acc = []) {
  if (!fs.existsSync(d)) return acc;
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p, acc);
    else if (e.name.endsWith(".json")) acc.push(p);
  }
  return acc.sort();
}

const siteMap = loadSiteMap();
const problems = [];
const pages = [];
for (const file of walk(DIR)) {
  const rel = path.relative(DIR, file).split(path.sep).join("/");
  const address = "/" + rel.replace(/\.json$/, "");
  const bad = (m) => problems.push(`content/pages/${rel}: ${m}`);
  let p;
  try {
    p = JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (e) {
    bad(`not valid JSON (${e.message})`);
    continue;
  }
  const a = parseAddress(address, siteMap);
  if (!a.ok) bad(`address ${address}: ${a.problems.join("; ")}`);
  else if (!KINDS.has(a.kind)) bad(`address ${address} is a ${a.kind}, not a glossary term, law or FAQ question`);
  if (a.ok && p.kind !== a.kind) bad(`"kind" is "${p.kind}", the address says ${a.kind}`);
  if (a.ok && p.country !== a.cc) bad(`"country" is "${p.country}", the address says ${a.cc}`);
  if (typeof p.title !== "string" || !p.title.trim()) bad(`"title" is missing`);
  if (typeof p.language !== "string" || !p.language) bad(`"language" is missing`);
  if (p.description !== undefined && typeof p.description !== "string") bad(`"description" must be text`);
  for (const k of ["published", "updated"]) if (p[k] !== undefined && !/^\d{4}-\d{2}-\d{2}$/.test(p[k])) bad(`"${k}" must be YYYY-MM-DD`);
  if (p.status !== undefined && !STATUSES.has(p.status)) bad(`unknown status "${p.status}"`);
  if (!Array.isArray(p.body) || !p.body.length) bad(`"body" is empty`);
  else
    p.body.forEach((b, i) => {
      if (!BLOCK_TYPES.has(b.type)) bad(`block ${i + 1}: unknown type "${b.type}"`);
      if (b.type === "table" && (!b.headers?.length || !b.rows?.every((r) => (Array.isArray(r) ? r : r?.cells)?.length))) bad(`block ${i + 1}: a table needs headers and rows of cells`);
    });
  pages.push({ ...p, address });
}
if (problems.length) {
  console.error("Page files have problems:\n  " + problems.join("\n  "));
  process.exit(1);
}
const out =
  `// GENERATED by scripts/build-page-index.mjs from content/pages. Do not edit by hand.\n` +
  `import type { PageRecord } from "@/types/page";\n\n` +
  `export const pageRecords = ${JSON.stringify(pages, null, 2)} as unknown as PageRecord[];\n`;
if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf8") !== out) fs.writeFileSync(OUT, out);
console.log(`page index: ${pages.length} page(s)`);
